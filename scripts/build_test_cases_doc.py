r"""Write docs/TEST_CASES.md from the test catalogue (tests/catalog.py), the tc() markers in the test files and the
latest recorded run in the reports database.

Run after a recorded test run (PowerShell):  .venv\Scripts\python.exe scripts\build_test_cases_doc.py
"""

import os
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")

import django  # noqa: E402

django.setup()

from django.utils import timezone  # noqa: E402

from testreports.models import TestSummary  # noqa: E402
from tests.catalog import TEST_CASES  # noqa: E402

MODULE_ORDER = ["Admin", "Customer", "Negative", "AI Recommendation", "End-to-End"]


def test_functions() -> dict[str, str]:
    """Test case id → 'tests/…/file.py::function'."""
    found = {}
    for path in (ROOT / "tests").rglob("test_*.py"):
        text = path.read_text(encoding="utf-8")
        for tc, fn in re.findall(r'@pytest\.mark\.tc\("([^"]+)"\)\s*\ndef (\w+)', text):
            found[tc] = f"{path.relative_to(ROOT).as_posix()}::{fn}"
    return found


def unit_test_counts() -> Counter:
    out = subprocess.run([sys.executable, "-m", "pytest", "tests/unit", "--collect-only", "-q", "--no-record", "-p", "no:randomly"],
                         cwd=ROOT, capture_output=True, text=True).stdout
    return Counter(line.split("::")[0] for line in out.splitlines() if "::" in line)


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def main():
    runs = list(TestSummary.objects.order_by("-execution_date")[:5])
    latest = runs[0] if runs else None
    results = {e.test_case_id: e for e in latest.executions.exclude(test_case=None)} if latest else {}
    functions = test_functions()
    lines = [
        "# Test cases",
        "",
        "The full catalogue of automated test cases (brief: Test Case table: id, test_name, module, test_description, "
        "expected_result) with the latest recorded result of each. The catalogue lives in `tests/catalog.py`; every case "
        "is one Playwright browser test linked to it with `@pytest.mark.tc(\"<id>\")`. This page is generated by "
        "`scripts/build_test_cases_doc.py` from the catalogue and the reports database.",
        "",
        "Run the tests with `.\\run_tests.ps1` (see the [README](../README.md#running-the-tests)). Every run is stored and "
        "shown on the admin **Test reports** page (`/manage/test-reports/`).",
        "",
    ]
    if latest:
        when = timezone.localtime(latest.execution_date).strftime("%d %b %Y, %H:%M")
        lines += [
            "## Latest run",
            "",
            f"Run {latest.pk}, {when} ({latest.browser_mode}): **{latest.passed_tests} passed, {latest.failed_tests} failed, "
            f"{latest.skipped_tests} skipped** of {latest.total_tests} tests in {latest.total_execution_time:.1f} s. "
            f"HTML report: `{latest.report_path}`.",
            "",
            "| Run | Date | Mode | Total | Passed | Failed | Skipped | Time |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for run in runs:
            when = timezone.localtime(run.execution_date).strftime("%d %b %Y, %H:%M")
            lines.append(f"| {run.pk} | {when} | {run.browser_mode} | {run.total_tests} | {run.passed_tests} | "
                         f"{run.failed_tests} | {run.skipped_tests} | {run.total_execution_time:.1f} s |")
        lines.append("")
    by_module = Counter(case["module"] for case in TEST_CASES.values())
    passed = Counter(TEST_CASES[tc]["module"] for tc, e in results.items() if e.status == "Passed" and tc in TEST_CASES)
    lines += ["## Coverage by module", "", "| Module | Test cases | Passed in the latest run |", "|---|---|---|"]
    for module in MODULE_ORDER:
        lines.append(f"| {module} | {by_module[module]} | {passed[module]} |")
    lines += [f"| **Total** | **{sum(by_module.values())}** | **{sum(passed.values())}** |", ""]
    for module in MODULE_ORDER:
        lines += [f"## {module}", "", "| ID | Test name | Description | Expected result | Test | Latest result |", "|---|---|---|---|---|---|"]
        for tc, case in TEST_CASES.items():
            if case["module"] != module:
                continue
            e = results.get(tc)
            result = f"{e.status} ({e.execution_time:.2f} s)" if e else "Not run yet"
            lines.append(f"| {tc} | {cell(case['test_name'])} | {cell(case['test_description'])} | {cell(case['expected_result'])} | "
                         f"`{functions.get(tc, 'missing')}` | {result} |")
        lines.append("")
    units = unit_test_counts()
    lines += [
        "## Unit tests",
        "",
        f"Besides the browser tests, {sum(units.values())} fast tests check the rules directly through Django's test "
        "client and the service functions (no browser). They are not catalogue cases; they run in every recorded run.",
        "",
        "| File | Tests |",
        "|---|---|",
    ]
    for path, n in sorted(units.items()):
        lines.append(f"| `{path}` | {n} |")
    lines += [
        "",
        "## How the tests stay reliable",
        "",
        "- They run against a separate test database (`test_db.sqlite3`, `test_reports.sqlite3`), flushed between tests; "
        "the shop's `db.sqlite3` is never opened.",
        "- Each test creates its own data with `tests/factories.py`, so any test can run alone (`pytest -k <name>`) or in "
        "any order (`.\\run_tests.ps1 -Random`).",
        "- Locators are roles, labels, visible text and `data-testid` only; waiting is done by Playwright's `expect`, "
        "never by fixed sleeps.",
        "- Each browser test checks what the user sees and what was stored in the database.",
        "- A failed test saves a screenshot to `reports/screenshots/<run>/`, embedded in that run's HTML report.",
        "",
    ]
    (ROOT / "docs" / "TEST_CASES.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"docs/TEST_CASES.md written: {len(TEST_CASES)} cases, latest run {latest.pk if latest else '-'}")


if __name__ == "__main__":
    main()
